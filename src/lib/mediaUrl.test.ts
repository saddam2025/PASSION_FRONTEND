import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { mediaSrcSet, mediaUrl, mediaVariantKeys } from './mediaUrl';

const key = 'media/2026/11/5990825a96164d768956c9804742a441-original.webp';
const stem = 'media/2026/11/5990825a96164d768956c9804742a441';

describe('public media URL resolver', () => {
  beforeEach(() => vi.stubEnv('VITE_MEDIA_BASE_URL', 'https://images.example.test/'));
  afterEach(() => vi.unstubAllEnvs());

  it('maps each display size to the backend variant name', () => {
    expect(mediaVariantKeys(key)).toEqual({
      thumb: `${stem}-thumb.webp`,
      medium: `${stem}-medium.webp`,
      large: `${stem}-large.webp`,
    });
    expect(mediaUrl(key, 'thumb')).toBe(`https://images.example.test/${stem}-thumb.webp`);
    expect(mediaUrl(key, 'medium')).toBe(`https://images.example.test/${stem}-medium.webp`);
    expect(mediaUrl(key, 'large')).toBe(`https://images.example.test/${stem}-large.webp`);
  });

  it('normalizes an already suffixed variant before resolving another size', () => {
    expect(mediaUrl(`${stem}-thumb.webp`, 'large')).toBe(`https://images.example.test/${stem}-large.webp`);
    expect(mediaUrl(`${stem}-large.webp`)).toBe(`https://images.example.test/${stem}-large.webp`);
  });

  it('uses the largest available backend variant when the requested one is absent', () => {
    const available = { thumb: `${stem}-thumb.webp`, medium: `${stem}-medium.webp` };
    expect(mediaUrl(key, 'large', available)).toBe(`https://images.example.test/${stem}-medium.webp`);
    expect(mediaUrl(key, 'thumb', { medium: available.medium })).toBe(`https://images.example.test/${stem}-medium.webp`);
  });

  it('falls back to the original stored object when no variant keys are available', () => {
    expect(mediaUrl(key, 'large', {})).toBe(`https://images.example.test/${key}`);
  });

  it('returns the default image for a missing key', () => {
    expect(mediaUrl('', 'large')).toBe('/images/course-cover-default.webp');
    expect(mediaVariantKeys('')).toBeUndefined();
    expect(mediaSrcSet('')).toBeUndefined();
  });

  it('falls back instead of requesting an object for a truncated upload id', () => {
    const truncatedKey = 'media/2026/11/5990825a96164d768956c9804742a44-original.webp';
    expect(mediaUrl(truncatedKey, 'large')).toBe('/images/course-cover-default.webp');
    expect(mediaVariantKeys(truncatedKey)).toBeUndefined();
  });

  it('normalizes an input extension to the WebP variant format generated by the backend', () => {
    const pngKey = `${stem}.png`;
    expect(mediaUrl(pngKey, 'large')).toBe(`https://images.example.test/${stem}-large.webp`);
  });

  it('builds srcset URLs using the backend names and responsive widths', () => {
    expect(mediaSrcSet(key)).toBe([
      `https://images.example.test/${stem}-thumb.webp 400w`,
      `https://images.example.test/${stem}-medium.webp 800w`,
      `https://images.example.test/${stem}-large.webp 1600w`,
    ].join(', '));
  });
});
